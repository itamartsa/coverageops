    oos_s        = Column(Integer, nullable=False, default=0)
    sum_sinr     = Column(Float, nullable=False, default=0.0)
    n_sinr       = Column(Integer, nullable=False, default=0)
    sum_rsrq     = Column(Float, nullable=False, default=0.0)
    n_rsrq       = Column(Integer, nullable=False, default=0)
    n_stale_excluded = Column(Integer, nullable=False, default=0)
    n_devices    = Column(SmallInteger, nullable=False, default=0)
