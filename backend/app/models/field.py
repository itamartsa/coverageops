    t0 = Column(Integer, nullable=False, default=0)
    t1 = Column(Integer, nullable=False, default=0)
    t2 = Column(Integer, nullable=False, default=0)
    t3 = Column(Integer, nullable=False, default=0)
    t4 = Column(Integer, nullable=False, default=0)
    t_unk = Column(Integer, nullable=False, default=0)
    w0 = Column(Integer, nullable=False, default=0)
