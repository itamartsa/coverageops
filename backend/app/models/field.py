"""
Field reception ("קליטה בשטח") — probe devices, measurements and aggregates.

Spec: docs/field/FIELD_DASHBOARD_SPEC.md section 2 (+ contract v2/v2.1 in
docs/field/API_CONTRACT.md). All tables are prefixed `field_` and are new, so
`create_all` creates them whole; later columns go through
core/migrations._ADDITIVE_COLUMNS as usual.

Conventions (as in the rest of the schema):
  * naive UTC DateTime (datetime.utcnow), ISO with "Z" in API output;
  * status-like columns are String(n) with documented values (no DB Enum);
  * JSON = JSON on SQLite, JSONB on PostgreSQL.
"""
from datetime import datetime

from sqlalchemy import (
    BigInteger, Boolean, Column, Date, DateTime, Float, ForeignKey, Index, Integer,
    JSON, SmallInteger, String, Uuid, text,
)
from sqlalchemy.dialects.postgresql import JSONB

from app.core.database import Base
from app.models import user  # noqa: F401  (FKs to users.id)

JSONType = JSON().with_variant(JSONB(), "postgresql")

# ── measurement flags (field_measurements.flags) ─────────────────────────────
FLAG_OUTSIDE_IL   = 2      # outside the Israel bbox (no grid)
FLAG_TS_FUTURE    = 4      # ts slightly in the future (≤ 5 min) — accepted as-is
FLAG_ANONYMIZED   = 8
FLAG_STALE_CELL   = 16     # cell_info_age_ms > FIELD_STALE_CELL_MS
FLAG_COARSE       = 32     # coarse location (loc_accuracy_m ≥ 1000 or 0.01° lattice)
FLAG_STALE_LOC    = 64     # loc_age_ms > FIELD_MAX_LOC_AGE_MS
FLAG_SENTINEL     = 128    # an Android "unavailable" sentinel was normalised to null
FLAG_AGE_UNKNOWN  = 256    # cell_info_age_ms is null (v2.1 rule 3)
FLAG_OUT_OF_RANGE = 512    # a radio value was out of range and nulled (v2.1 rule 4)


